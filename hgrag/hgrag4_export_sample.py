def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _subset_passages(passages: List[Dict[str, Any]],
                     n: int) -> List[Dict[str, Any]]:
    """取前 n 个段落, 并补齐 pid 以便与图谱对上。"""
    return passages[:n] if n > 0 else passages


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(description="导出 HGRAG 可分发基准样本")
    p.add_argument("--kg-dir", default=r"C:\data\zsk\RAG\kgv4")
    p.add_argument("--results-dir", default=r"C:\data\zsk\RAG\hgrag4\results")
    p.add_argument("--out-dir", default="release/hgrag4_sample")
    p.add_argument("--n-passages", type=int, default=DEFAULT_N_PASSAGES,
                   help="分发的段落数, 0 = 全部")
    p.add_argument("--n-questions", type=int, default=DEFAULT_N_QUESTIONS,
                   help="分发的问题数, 0 = 全部")
    p.add_argument("--full", action="store_true",
                   help="分发完整语料与全部问题 (HotpotQA 为公开发布, "
                        "可整份分发)")
    args = p.parse_args(argv)

    if args.full:
        args.n_passages = 0
        args.n_questions = 0

    out = os.path.abspath(args.out_dir)
    if os.path.isdir(out):
        shutil.rmtree(out)
    # kg/ 与 results/ 两个子目录: kg/ 的布局与 hgrag4_run.py --kg-dir 期望的
    # 布局一致 (passages/questions/entities/relations/activation_network/
    # splits 同级), 因此读者可以直接
    #     python hgrag4_run.py --kg-dir sample/kg
    # 无需任何路径改写。
    for sub in ("kg", "results"):
        os.makedirs(os.path.join(out, sub), exist_ok=True)

    # ---------------- corpus ---------------- #
    passages = A.read_json(os.path.join(args.kg_dir, "passages.json")) or []
    questions = A.read_json(os.path.join(args.kg_dir, "questions.json")) or []
    splits = A.read_json(os.path.join(args.kg_dir, "splits.json")) or {}

    sub_passages = _subset_passages(passages, args.n_passages)
    kept_pids = {p.get("pid") for p in sub_passages}
    kept_titles = {p.get("title") for p in sub_passages}

    # 问题: 只保留其 gold 段落仍在样本中的那些, 保证样本自洽
    sub_questions = []
    for q in questions:
        gold = set(q.get("gold_titles") or [])
        if args.n_questions > 0 and len(sub_questions) >= args.n_questions:
            break
        if args.n_passages > 0 and gold and not (gold & kept_titles):
            continue
        sub_questions.append(q)

    A.write_json(os.path.join(out, "kg", "passages.json"), sub_passages)
    A.write_json(os.path.join(out, "kg", "questions.json"), sub_questions)
    A.write_json(os.path.join(out, "kg", "splits.json"), splits)

    # ---------------- graph ---------------- #
    entities = A.read_json(os.path.join(args.kg_dir, "entities.json")) or []
    relations = A.read_json(os.path.join(args.kg_dir, "relations.json")) or []
    network = A.read_json(os.path.join(args.kg_dir,
                                      "activation_network.json")) or {}

    # 只保留仍出现在样本段落中的实体/关系/节点/边, 使样本图自洽。
    # 实体通过 source_pids 与段落关联, 关系通过 source_pid 关联。
    sub_entities = [e for e in entities
                     if kept_pids & set(e.get("source_pids") or [])]
    kept_eids = {e.get("eid") for e in sub_entities}
    sub_relations = [r for r in relations
                     if r.get("source_pid") in kept_pids
                     and r.get("source") in kept_eids
                     and r.get("target") in kept_eids]

    # 注意: 节点字典的标识键是 "eid" (见 activation_graphrag.py 中
    # ActivationRetriever 读取 network["nodes"] 的方式), 不是 "id"。
    # 早前的版本误用 n.get("id"), 于是 kept_node_ids 变成 {None},
    # 所有边都被过滤掉 —— 导出的样本图有节点却没有边, 扩散机制
    # (论文的核心算子) 完全失效, 而显著性检验仍能通过 (因为它
    # 复算用的是预存的逐题向量), 所以这个缺陷不会自己暴露出来。
    nodes = network.get("nodes") or []
    edges = network.get("edges") or []
    sub_nodes = [n for n in nodes
                 if n.get("eid") in kept_eids
                 or kept_pids & set(n.get("source_pids") or [])]
    kept_node_ids = {n.get("eid") for n in sub_nodes}
    sub_edges = [e for e in edges
                 if e.get("source") in kept_node_ids
                 and e.get("target") in kept_node_ids]

    sub_network = dict(network)
    sub_network["nodes"] = sub_nodes
    sub_network["edges"] = sub_edges

    A.write_json(os.path.join(out, "kg", "entities.json"), sub_entities)
    A.write_json(os.path.join(out, "kg", "relations.json"), sub_relations)
    A.write_json(os.path.join(out, "kg", "activation_network.json"),
                 sub_network)

    raw = os.path.join(args.kg_dir, "raw_extractions.jsonl")
    if os.path.exists(raw):
        shutil.copy2(raw, os.path.join(out, "kg", "raw_extractions.jsonl"))

    # ---------------- results ---------------- #
    n_res = 0
    for name in RESULT_FILES:
        src = os.path.join(args.results_dir, name)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(out, "results", name))
            n_res += 1

    # ---------------- README + MANIFEST ---------------- #
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as fh:
        fh.write(README)

    manifest: Dict[str, Any] = {
        "name": "HGRAG benchmark sample",
        "source_paper": "Association by Design: A Brain-Inspired Hybrid "
                        "Retrieval Architecture for Multi-Hop "
                        "Retrieval-Augmented Generation (HGRAG)",
        "benchmark": "HotpotQA distractor split (official public release)",
        "split_seed": 20240917,
        "n_passages_in_sample": len(sub_passages),
        "n_passages_full": len(passages),
        "n_questions_in_sample": len(sub_questions),
        "n_questions_full": len(questions),
        "n_result_files": n_res,
        "graph_in_sample": {
            "entities": len(sub_entities),
            "relations": len(sub_relations),
            "nodes": len(sub_nodes),
            "edges": len(sub_edges),
        },
        "graph_full": {
            "entities": len(entities),
            "relations": len(relations),
            "nodes": len(nodes),
            "edges": len(edges),
        },
        "files": [],
    }
    for root, _dirs, files in os.walk(out):
        for fn in sorted(files):
            if fn == "MANIFEST.json":
                continue
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, out).replace("\\", "/")
            manifest["files"].append({
                "path": rel,
                "bytes": os.path.getsize(full),
                "sha256": _sha256(full),
            })
    manifest["n_files"] = len(manifest["files"])

    # ---------------- 自检 ---------------- #
    # 导出的样本图必须仍然带边: 扩散 (spreading activation) 是论文的
    # 核心算子, 一个没有边的图无法复现 graph route, 第三方拿到这样的
    # 样本也无法复现论文的检索结果。这里显式失败而不是静默地产出一
    # 个空图 —— 静默失败正是这个缺陷当初没有被发现的原因。
    if sub_nodes and not sub_edges:
        raise SystemExit(
            "导出失败: 样本图有 %d 个节点却没有任何边, 扩散机制无法复现。"
            "请检查 activation_network.json 的节点标识键 (应为 'eid') "
            "与边的 source/target 是否匹配。" % len(sub_nodes)
        )
    if sub_nodes:
        _deg: Dict[str, int] = {}
        for e in sub_edges:
            _deg[e["source"]] = _deg.get(e["source"], 0) + 1
            _deg[e["target"]] = _deg.get(e["target"], 0) + 1
        _isolated = sum(1 for n in sub_nodes if _deg.get(n.get("eid"), 0) == 0)
        if _isolated:
            print("警告: %d / %d 个样本节点在子图内没有邻居 (原图即如此, "
                  "非导出缺陷)" % (_isolated, len(sub_nodes)))

    with open(os.path.join(out, "MANIFEST.json"), "w",
              encoding="utf-8") as fh:
        json.dump(manifest, fh, ensure_ascii=False, indent=1)

    print(f"样本已导出到: {out}")
    print(f"  段落: {len(sub_passages)} / {len(passages)}")
    print(f"  问题: {len(sub_questions)} / {len(questions)}")
    print(f"  图: 实体 {len(sub_entities)}, 关系 {len(sub_relations)}, "
          f"节点 {len(sub_nodes)}, 边 {len(sub_edges)}")
    print(f"  结果文件: {n_res}")
    print(f"  清单文件: {manifest['n_files']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
